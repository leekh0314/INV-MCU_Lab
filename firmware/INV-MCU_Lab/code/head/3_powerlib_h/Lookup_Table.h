#ifndef __LOOKUP_TABLE_H_
#define __LOOKUP_TABLE_H_

/*------------------------------------------------------------------------------
 * 查找表结构体：用于一维线性插值计算
 *------------------------------------------------------------------------------*/
typedef struct
{ 
    unsigned short int Table_Length;  // 查找表长度（点的数量，x/y 轴一一对应）
                     int x_Axis_In;   // 输入值（需要查找或插值的横坐标）
                     int y_Axis_Out;  // 输出值（插值计算后的结果）
                     int *x_Axis_Ptr; // 指向 x 轴数组（查找表横坐标序列，需升序排列）
                     int *y_Axis_Ptr; // 指向 y 轴数组（查找表纵坐标序列，与 x 对应）
                void (*Calc)();       // 函数指针：计算函数（通常指向 Lookup_Table_Calc）
} Lookup_Table;

/** @brief 查找表句柄（指针类型） */
typedef Lookup_Table *Lookup_Table_Handle;

/*------------------------------------------------------------------------------
 * 宏：查找表默认初始化
 * 用于快速生成一个空表对象，所有指针为空。
 *------------------------------------------------------------------------------*/
#define LOOKUP_TABLE_DEFAULTS { 0, \
                                0, \
                                0, \
                                (void *)0, \
                                (void *)0, \
                                (void *)0 }

#endif /* __LOOKUP_TABLE_H_ */

/*------------------------------------------------------------------------------
 * 外部变量声明
 *------------------------------------------------------------------------------*/
extern Lookup_Table Lookup_Table_Speed;  // 全局查找表对象（示例：用于速度映射）

/*------------------------------------------------------------------------------
 * 函数声明
 *------------------------------------------------------------------------------*/
void Lookup_Table_Calc(Lookup_Table_Handle);  // 查找表计算函数：执行线性插值
